import { writeFile, mkdir } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

// Constellation stick figures from Stellarium's "modern" sky culture (index.json), by the Stellarium team.
// Licence of that data (from the sky culture's own description.md): "Text and data: CC BY-SA 4.0".
// Pin STELLARIUM_COMMIT to the exact commit of github.com/Stellarium/stellarium you checked, so the licence
// you read is the licence of the data you shipped.
const STELLARIUM_COMMIT = 'PASTE_STELLARIUM_COMMIT_HASH';
const UNPINNED = STELLARIUM_COMMIT.startsWith('PASTE_');
const SOURCE_URL = `https://raw.githubusercontent.com/Stellarium/stellarium/${UNPINNED ? 'master' : STELLARIUM_COMMIT}/skycultures/modern/index.json`;
const OUTPUT_URL = process.env.OUT_DIR
  ? new URL('constellationLines.ts', `file://${process.env.OUT_DIR}/`)
  : new URL('./src/data/constellationLines.ts', import.meta.url);

async function fetchIndex() {
  const res = await fetch(SOURCE_URL);
  if (!res.ok) {
    throw new Error(`Failed to fetch modern sky culture index.json: ${res.status} ${res.statusText}`);
  }
  return res.json();
}

/** Each constellation has polylines of Hipparcos numbers; turn every polyline into consecutive pairs. */
function toPairs(index) {
  const pairs = [];
  for (const constellation of index.constellations) {
    for (const polyline of constellation.lines ?? []) {
      for (let i = 0; i + 1 < polyline.length; i++) {
        const a = Number(polyline[i]);
        const b = Number(polyline[i + 1]);
        if (!Number.isInteger(a) || !Number.isInteger(b) || a <= 0 || b <= 0) {
          throw new Error(`Unexpected line endpoint in ${constellation.id}: ${polyline[i]} -> ${polyline[i + 1]}`);
        }
        pairs.push([a, b]);
      }
    }
  }
  return pairs;
}

function toModule(pairs) {
  const rows = pairs.map(([a, b]) => `  [${a}, ${b}],`).join('\n');
  return `/**
 * Auto-generated by generate-constellations.mjs. Do not edit by hand.
 *
 * Source: Stellarium "modern" sky culture (skycultures/modern/index.json), by the Stellarium team.
 * https://github.com/Stellarium/stellarium (commit ${UNPINNED ? 'UNPINNED' : STELLARIUM_COMMIT})
 * Licence: text and data CC BY-SA 4.0 - https://creativecommons.org/licenses/by-sa/4.0/
 * Modified for oneSky: polylines of Hipparcos star numbers converted to pairs [hipA, hipB].
 * This file is itself shared under CC BY-SA 4.0.
 */
export const CONSTELLATION_LINES: [number, number][] = [
${rows}
];
`;
}

async function main() {
  if (UNPINNED && !process.argv.includes('--allow-unpinned')) {
    console.error('STELLARIUM_COMMIT is not set at the top of this script. Pin it, or pass --allow-unpinned.');
    process.exitCode = 1;
    return;
  }
  const index = await fetchIndex();
  const pairs = toPairs(index);
  const module = toModule(pairs);

  const outPath = fileURLToPath(OUTPUT_URL);
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, module, 'utf8');

  console.log(`Parsed ${pairs.length} line segments, wrote ${outPath}`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
